export async function loadForecastAssets() {
  const [times, sites, shoreline, frameUrls] = await Promise.all([
    timesFile.json(),
    sitesFile.json(),
    shorelineFile.json(),
    Promise.all(frameFiles.map((file) => file.url())),
  ]);

  return {times, sites, shoreline, frameUrls};
}
